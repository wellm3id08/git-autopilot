// GIT_AUTOPILOT_LANG=en or =es overrides the system language.
var useSpanish = sync.OnceValue(func() bool {
	l := os.Getenv("GIT_AUTOPILOT_LANG")
	if l == "" {
		l = string(lang.SystemLocale())
	}
	return strings.HasPrefix(strings.ToLower(l), "es")
})

func T(s string) string {
	if useSpanish() {
		if t, ok := spanish[s]; ok {
			return t
		}
	}
	return s
}

func Tf(format string, args ...any) string {
	return fmt.Sprintf(T(format), args...)
}

